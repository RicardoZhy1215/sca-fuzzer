"""
Arms of the generator bandit: (instruction group) x (input value mix).

An arm is a Revizor config that includes common.yaml and sets instruction_categories /
instruction_allowlist / input_value_mix. Instruction groups are built from the spec file:
isa_spec.py drops every f32/f64-typed instruction unless allowlisted BY NAME, so the *-fp groups
list those names explicitly and the *-int groups get only what the categories let through.

  python rvzr/SpecRL/genbandit/arms.py            # (re)write arms/*.yaml and validate each
"""
import json
import os
import sys
from typing import Dict, List

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "../../.."))
SPEC = os.path.join(ROOT, "base-avx.json")
ARMS_DIR = os.path.join(HERE, "arms")

BASE = ["BASE-BINARY", "BASE-BITBYTE", "BASE-CMOV", "BASE-CONVERT", "BASE-DATAXFER",
        "BASE-FLAGOP", "BASE-LOGICAL", "BASE-MISC", "BASE-NOP", "BASE-ROTATE", "BASE-SEMAPHORE",
        "BASE-SETCC", "BASE-SHIFT", "BASE-WIDENOP"]
SSE = ["SSE-SSE", "SSE-DATAXFER", "SSE-MISC", "SSE-CONVERT", "SSE2-SSE", "SSE2-DATAXFER",
       "SSE2-MISC", "SSE2-LOGICAL", "SSE2-CONVERT", "SSE3-SSE", "SSE3-DATAXFER", "SSE4-SSE",
       "SSE4-LOGICAL"]
AVX = ["AVX-AVX", "AVX-DATAXFER", "AVX-LOGICAL", "AVX-BROADCAST", "AVX2-AVX2", "AVX2-DATAXFER",
       "AVX2-LOGICAL", "AVX2-BROADCAST"]
# not in the DR backend's category list; their FP-typed names come in through the allowlist
SSE_EXTRA = ["SSE-LOGICAL_FP", "SSE2-LOGICAL_FP"]
AVX_EXTRA = ["AVX-CONVERT", "AVX-LOGICAL_FP"]

FP_XTYPES = {"f16", "f32", "f64", "f80", "bf16"}
# names that also match BASE-STRINGOP (allowlisting them pulls the string op in), names on the
# x86 blocklist (the allowlist would override it), and the masked moves (common.yaml)
NEVER_ALLOW = {"cmpsd", "movsd", "ldmxcsr", "stmxcsr", "vldmxcsr", "vstmxcsr", "vmaskmovps",
               "vmaskmovpd", "vpmaskmovd", "vpmaskmovq", "maskmovdqu", "vmaskmovdqu",
               "rsqrtps", "rsqrtss", "rcpps", "rcpss", "cmpps", "cmpss", "cmppd"}
# ...except the approximations / FP compares, which the DR model executes natively and which
# the arch checks passed: keep them allowed
NEVER_ALLOW -= {"rsqrtps", "rsqrtss", "rcpps", "rcpss", "cmpps", "cmpss", "cmppd"}

MIXES = ["default", "full64", "special"]


def fp_names(spec: List[dict], categories: List[str]) -> List[str]:
    names = {i["name"] for i in spec if i["category"] in categories
             and any(o["type_"] == "REG" and o.get("xtype") in FP_XTYPES for o in i["operands"])}
    return sorted(names - NEVER_ALLOW)


def groups(spec: List[dict]) -> Dict[str, Dict[str, List[str]]]:
    sse_fp = fp_names(spec, SSE + SSE_EXTRA)
    avx_fp = fp_names(spec, AVX + AVX_EXTRA)
    return {
        "base": {"categories": BASE, "allow": []},
        "sseint": {"categories": BASE + SSE, "allow": []},
        "ssefp": {"categories": BASE + SSE, "allow": sse_fp},
        "avxint": {"categories": BASE + AVX, "allow": []},
        "avxfp": {"categories": BASE + AVX, "allow": avx_fp},
        "all": {"categories": BASE + SSE + AVX, "allow": sse_fp + avx_fp},
    }


def arm_names() -> List[str]:
    spec = json.load(open(SPEC))
    return [f"{g}-{m}" for g in groups(spec) for m in MIXES]


CONTROL = "all-default"   # = standard Revizor over the whole instruction set


def write_arms() -> List[str]:
    spec = json.load(open(SPEC))
    os.makedirs(ARMS_DIR, exist_ok=True)
    out = []
    for g, d in groups(spec).items():
        for m in MIXES:
            name = f"{g}-{m}"
            lines = ["# generated by arms.py -- do not edit", "file: !include common.yaml",
                     f"input_value_mix: {m}", "instruction_categories:"]
            lines += [f"  - {c}" for c in d["categories"]]
            if d["allow"]:
                lines += ["instruction_allowlist:"] + [f"  - {n}" for n in d["allow"]]
            path = os.path.join(ARMS_DIR, f"{name}.yaml")
            open(path, "w").write("\n".join(lines) + "\n")
            out.append(path)
    return out


def validate(path: str) -> str:
    """Load the arm exactly as `revizor.py fuzz` would and summarize its instruction set."""
    sys.path.insert(0, ROOT)
    import warnings
    warnings.filterwarnings("ignore")
    from rvzr.config import CONF
    from rvzr.isa_spec import InstructionSet
    from rvzr.arch.x86.fuzzer import _update_instruction_list
    CONF.load(path, HERE)
    _update_instruction_list()
    iset = InstructionSet(SPEC, CONF.instruction_categories)
    names = {s.name for s in iset.instructions}
    fp = [n for n in names if n in set(fp_names(json.load(open(SPEC)), SSE + SSE_EXTRA + AVX + AVX_EXTRA))]
    bad = sorted(n for n in names if "maskmov" in n or n in ("ud2", "int1", "int3"))
    assert not bad, f"{path}: forbidden instructions present: {bad}"
    return (f"{os.path.basename(path):22s} mix={CONF.input_value_mix:8s} names={len(names):4d} "
            f"fp={len(fp):3d} ymm-capable={sum(1 for n in names if n.startswith('v')):3d}")


if __name__ == "__main__":
    for p in write_arms():
        # a fresh interpreter per arm: CONF is a process-wide singleton
        os.system(f"{sys.executable} -c \"import sys; sys.path.insert(0, '{HERE}'); "
                  f"import arms; print(arms.validate('{p}'))\" 2>/dev/null")
